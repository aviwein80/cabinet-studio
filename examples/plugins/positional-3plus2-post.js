// @plugin positional-3plus2-post
// @name Positional 3+2 post (sample)
// @version 1.0
// @description A script post for a router with two rotary axes for positional (3+2) machining: each operation turns the two axes to its locked angles with the tool retracted, then cuts with X Y Z only. X Y Z are the machine's axes as worked out by the app's own kinematics for that machine model, written against a work offset at the part's origin with every rotary axis at 0 (G54). An example to adapt to a real controller (its retract line, which way its axes turn, whether it keeps the tool tip on the point). Not machine-validated. It only produces programs with the machine-output grant, the script-post and 3+2-post switches on, a machine model with two rotary axes for 3+2, a machine other than the N-200, and a clean export check.
// @author Cabinet Studio
// @machine-output

// The line that sends Z to its safe position before the rotary axes turn. Controller-specific:
// change it for the real machine.
var RETRACT = 'G53 G0 Z0'

cs.post.add({
  id: 'positional-3plus2',
  name: 'Positional 3+2 router (script sample)',
  ext: 'nc',
  description: 'Metric, absolute, G54 at the part origin with the rotary axes at 0. Per operation: retract, turn both rotary axes (locked angles, degrees), then G0/G1 in X Y Z (drill cycles written as straight moves along the tilted tool). Flat operations run with both axes at 0.',
  run: function (input) {
    var out = []
    var n = function (v) { return v.toFixed(3) }
    var lastF = null
    var f = function (v) {
      var s = String(v)
      if (s === lastF) return ''
      lastF = s
      return ' F' + s
    }
    out.push('%', '(' + input.name + ')', '(GENERATED BY CABINET STUDIO - NOT MACHINE-VALIDATED)', 'G21 G90 G17 G94 G54')
    var turned = null
    input.ops.forEach(function (op) {
      var p = op.positional
      if (!p) {
        // not converted: a post must not guess the machine's axes
        out.push('(' + op.name + ': NOT A 3+2 OPERATION - NOT WRITTEN)')
        return
      }
      if (op.tool) out.push('(T' + op.tool.number + ' ' + op.tool.name + ')', 'T' + op.tool.number + ' M6', 'S' + op.rpm + ' M3')
      out.push('(' + op.name + ')')
      var a = p.letters[0] + n(p.angles[0]) + ' ' + p.letters[1] + n(p.angles[1])
      out.push('(3+2: ' + a + (p.plane ? ', PLANE ' + p.plane.name.toUpperCase() : ', FLAT') + (p.tcp ? ', TIP CONTROL ON' : '') + ')')
      if (turned !== a) {
        out.push(RETRACT, 'G0 ' + a)
        turned = a
        lastF = null
      }
      // the work offset: the part's origin with every rotary axis at 0
      var w = p.partAt
      op.moves.forEach(function (m) {
        var xyz = ' X' + n(m.x - w.x) + ' Y' + n(m.y - w.y) + ' Z' + n(m.z - w.z)
        if (m.t === 'rapid') out.push('G0' + xyz)
        else out.push('G1' + xyz + f(m.f))
      })
    })
    out.push('M5', RETRACT, 'M30', '%')
    // no trailing spaces, single spaces between words, no empty lines
    return out
      .map(function (l) { return l.replace(/\s+$/, '').replace(/ {2,}/g, ' ') })
      .filter(function (l) { return l.length > 0 })
      .join('\r\n') + '\r\n'
  },
})
