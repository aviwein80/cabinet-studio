/**
 * M3.3 rotary output (acceptance: "output only through a script post for a machine model with a
 * rotary axis; the N-200 export refuses it"). The sample rotary script post writes a turned part's
 * program for a router whose machine model declares an A axis, only with every switch on and the
 * grant; everything else is refused with its reason.
 */
import fs from 'node:fs'
import path from 'node:path'
