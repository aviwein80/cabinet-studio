// @plugin iso-router-post
// @name ISO router post (sample)
// @version 1.0
// @description A script post that writes the same G-code as the built-in "Generic ISO router (sample)" template, as an example to copy for another controller. Not machine-validated. It only produces programs with the machine-output grant, the "Write programs through script posts" switch on, a machine other than the N-200, and a clean export check.
// @author Cabinet Studio
// @machine-output

cs.post.add({
  id: 'iso-router',
  name: 'Generic ISO router (script sample)',
  ext: 'nc',
  description: 'Metric, absolute, G2/G3 arcs with I and J, G81/G83 drilling cycles, F only when it changes.',
  run: function (input) {
    var out = []
    var n = function (v) { return v.toFixed(3) }
    var lastF = null
    // a feed word only when the value changes
    var f = function (v) {
      var s = String(v)
      if (s === lastF) return ''
      lastF = s
      return ' F' + s
    }
    out.push('%', '(' + input.name + ')', '(GENERATED BY CABINET STUDIO - NOT MACHINE-VALIDATED)', 'G21 G90 G17')
    input.ops.forEach(function (op) {
      if (op.tool) out.push('(T' + op.tool.number + ' ' + op.tool.name + ')', 'T' + op.tool.number + ' M6', 'S' + op.rpm + ' M3')
      out.push('(' + op.name + ')')
      op.moves.forEach(function (m) {
        var xyz = ' X' + n(m.x) + ' Y' + n(m.y) + ' Z' + n(m.z)
        if (m.t === 'rapid') out.push('G0' + xyz)
        else if (m.t === 'feed') out.push('G1' + xyz + f(m.f))
        else if (m.t === 'arc') out.push((m.ccw ? 'G3' : 'G2') + xyz + ' I' + n(m.i) + ' J' + n(m.j) + f(m.f))
        else if (m.peck > 0) out.push('G83' + xyz + ' R' + n(m.r) + ' Q' + n(m.peck) + f(m.f), 'G80')
        else out.push('G81' + xyz + ' R' + n(m.r) + f(m.f), 'G80')
      })
    })
    out.push('M5', 'G0 Z50', 'M30', '%')
    // no trailing spaces, single spaces between words
    return out.map(function (l) { return l.replace(/\s+$/, '').replace(/ {2,}/g, ' ') }).join('\r\n') + '\r\n'
  },
})
