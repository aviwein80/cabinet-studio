// @plugin simultaneous-5axis-post
// @name Simultaneous 5-axis post (sample)
// @version 1.0
// @description A script post for a router whose two rotary axes move while it cuts (simultaneous 5-axis). Every move is written with X Y Z and both rotary axes, as worked out by the app's own kinematics for that machine model, against a work offset at the part's origin with every rotary axis at 0 (G54). Feed moves on which a rotary axis turns are written with inverse-time feeds (G93); the others in mm/min (G94). An example to adapt to a real controller (its retract line, which way its axes turn, its tool-centre-point mode, its inverse-time rules). Not machine-validated. It only produces programs with the machine-output grant, the script-post and 5-axis-post switches on, a machine model with simultaneous 5-axis, a machine other than the N-200, toolpaths from a licensed 5-axis engine and a clean export check.
// @author Cabinet Studio
// @machine-output

// The line that sends Z to its safe position before the rotary axes turn between operations.
// Controller-specific: change it for the real machine.
var RETRACT = 'G53 G0 Z0'

cs.post.add({
  id: 'simultaneous-5axis',
  name: 'Simultaneous 5-axis router (script sample)',
  ext: 'nc',
  description: 'Metric, absolute, G54 at the part origin with the rotary axes at 0. Per operation: retract, turn both rotary axes to where it starts, then every move as G0/G1 X Y Z with both rotary axes; G93 inverse-time feeds on moves where a rotary axis turns, G94 mm/min on the others.',
  run: function (input) {
    var out = []
    var n = function (v) { return v.toFixed(3) }
    var mode = null
    var setMode = function (m) {
      if (m === mode) return ''
      mode = m
      return m + ' '
    }
    out.push('%', '(' + input.name + ')', '(GENERATED BY CABINET STUDIO - NOT MACHINE-VALIDATED)', 'G21 G90 G17 G94 G54')
    mode = 'G94'
    input.ops.forEach(function (op) {
      var p = op.multiAxis
      if (!p) {
        // not converted: a post must not guess the machine's axes
        out.push('(' + op.name + ': NOT CONVERTED FOR 5-AXIS - NOT WRITTEN)')
        return
      }
      if (!p.moves.length) return
      if (op.tool) out.push('(T' + op.tool.number + ' ' + op.tool.name + ')', 'T' + op.tool.number + ' M6', 'S' + op.rpm + ' M3')
      out.push('(' + op.name + ')')
      out.push('(5-AXIS: ' + p.letters[0] + '/' + p.letters[1] + ', ' + (p.simultaneous ? 'SIMULTANEOUS' : 'ANGLES HELD') + ', ' + (p.solution === 'other' ? 'OTHER SOLUTION' : 'USUAL SOLUTION') + (p.tcp ? ', TIP CONTROL ON' : '') + ')')
      var w = p.partAt
      var first = p.moves[0]
      var ab = function (m) { return ' ' + p.letters[0] + n(m.a1) + ' ' + p.letters[1] + n(m.a2) }
      out.push(RETRACT, 'G0' + ab(first))
      var prev = null
      p.moves.forEach(function (m) {
        var xyz = ' X' + n(m.x - w.x) + ' Y' + n(m.y - w.y) + ' Z' + n(m.z - w.z) + ab(m)
        if (m.t === 'rapid') {
          out.push('G0' + xyz)
        } else {
          var turns = prev && (Math.abs(m.a1 - prev.a1) > 1e-9 || Math.abs(m.a2 - prev.a2) > 1e-9)
          if (turns && m.len > 1e-6) {
            // inverse time: moves per minute = feed (mm/min) / tip travel (mm)
            out.push(setMode('G93') + 'G1' + xyz + ' F' + (m.f / m.len).toFixed(3))
          } else {
            out.push(setMode('G94') + 'G1' + xyz + ' F' + m.f)
          }
        }
        prev = m
      })
    })
    out.push(setMode('G94') + 'M5', RETRACT, 'M30', '%')
    // no trailing spaces, single spaces between words, no empty lines
    return out
      .map(function (l) { return l.replace(/\s+$/, '').replace(/ {2,}/g, ' ') })
      .filter(function (l) { return l.length > 0 })
      .join('\r\n') + '\r\n'
  },
})
