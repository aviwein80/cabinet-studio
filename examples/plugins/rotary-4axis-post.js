// @plugin rotary-4axis-post
// @name Rotary 4-axis post (sample)
// @version 1.0
// @description A script post for a router with a rotary axis (A turning about X, B about Y, C about Z): rotary operations are written against the rotary axis with the rotary word in degrees, inverse-time feeds (G93) on moves that turn the axis. An example to adapt to a real controller (check which way your rotary axis turns, and its work offset). Not machine-validated. It only produces programs with the machine-output grant, the script-post and rotary-post switches on, a machine model that declares the rotary axis, a machine other than the N-200, and a clean export check.
// @author Cabinet Studio
// @machine-output

cs.post.add({
  id: 'rotary-4axis',
  name: 'Rotary 4-axis router (script sample)',
  ext: 'nc',
  description: 'Metric, absolute. Rotary operations: X Y Z against the rotary axis (work offset on the axis) and A/B/C in degrees, G93 inverse-time feeds on moves that turn the axis, G94 mm/min otherwise. Flat operations as in the ISO sample.',
  run: function (input) {
    var out = []
    var n = function (v) { return v.toFixed(3) }
    var mode = null
    var lastF = null
    // G93 / G94 only when it changes; a feed word only when its value changes (or the mode did)
    var feedMode = function (m) {
      if (m === mode) return ''
      mode = m
      lastF = null
      return m + ' '
    }
    var f = function (v) {
      var s = String(v)
      if (s === lastF) return ''
      lastF = s
      return ' F' + s
    }
    out.push('%', '(' + input.name + ')', '(GENERATED BY CABINET STUDIO - NOT MACHINE-VALIDATED)', 'G21 G90 G17')
    input.ops.forEach(function (op) {
      if (op.tool) out.push('(T' + op.tool.number + ' ' + op.tool.name + ')', 'T' + op.tool.number + ' M6', 'S' + op.rpm + ' M3')
      out.push('(' + op.name + ')')
      if (op.rotary) {
        var L = op.rotary.letter
        out.push('(ROTARY ' + L + ' ABOUT ' + op.rotary.axis + ': WORK OFFSET ON THE AXIS, ' + L + '0 = TOOL STRAIGHT ABOVE)')
        var lastA = null
        op.moves.forEach(function (m) {
          var words = ' X' + n(m.x) + ' Y' + n(m.y) + ' Z' + n(m.z) + ' ' + L + n(m.a)
          if (m.t === 'rapid') out.push('G0' + words)
          else {
            // turning the axis: inverse time, 1 / minutes for the move, from the tip's feed and travel
            var turns = lastA !== null && Math.abs(m.a - lastA) > 1e-9
            if (turns && m.len > 1e-6) out.push(feedMode('G93') + 'G1' + words + f(Math.round((m.f / m.len) * 1000) / 1000))
            else out.push(feedMode('G94') + 'G1' + words + f(m.f))
          }
          lastA = m.a
        })
        out.push(feedMode('G94').trim())
        return
      }
      op.moves.forEach(function (m) {
        var xyz = ' X' + n(m.x) + ' Y' + n(m.y) + ' Z' + n(m.z)
        if (m.t === 'rapid') out.push('G0' + xyz)
        else if (m.t === 'feed') out.push(feedMode('G94') + 'G1' + xyz + f(m.f))
        else if (m.t === 'arc') out.push(feedMode('G94') + (m.ccw ? 'G3' : 'G2') + xyz + ' I' + n(m.i) + ' J' + n(m.j) + f(m.f))
        else if (m.peck > 0) out.push('G83' + xyz + ' R' + n(m.r) + ' Q' + n(m.peck) + f(m.f), 'G80')
        else out.push('G81' + xyz + ' R' + n(m.r) + f(m.f), 'G80')
      })
    })
    out.push('M5', 'G0 Z50', 'M30', '%')
    // no trailing spaces, single spaces between words, no empty lines
    return out
      .map(function (l) { return l.replace(/\s+$/, '').replace(/ {2,}/g, ' ') })
      .filter(function (l) { return l.length > 0 })
      .join('\r\n') + '\r\n'
  },
})
